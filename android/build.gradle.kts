    afterEvaluate {
        if (plugins.hasPlugin("com.android.application") || plugins.hasPlugin("com.android.library")) {
            extensions.configure<com.android.build.api.dsl.CommonExtension> {
                compileSdk = 37
                defaultConfig.minSdk = 23
            }
        }
    }
}

subprojects {
    project.evaluationDependsOn(":app")
}

